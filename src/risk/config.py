"""Configuration for the Deterministic Risk Engine (Phase 7).

Manages factor weights, category mappings, normalization scales, risk bands,
and academic taxonomy distinctions (HEURISTIC RISK vs MODEL OUTPUT vs GROUND TRUTH).
"""
from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Mapping


class RiskClassificationType(str, Enum):
    """Explicit taxonomy to distinguish risk score provenance and epistemology.

    - HEURISTIC_RISK: Rule-based, domain-weighted deterministic calculation.
                      Not a ground-truth label nor a machine-learned prediction.
    - MODEL_OUTPUT:   Predicted representation generated by GraphSAGE / GAT / ML models.
    - GROUND_TRUTH:   Empirically verified, post-disruption real-world operational outcome.
    """
    HEURISTIC_RISK = "HEURISTIC_RISK"
    MODEL_OUTPUT = "MODEL_OUTPUT"
    GROUND_TRUTH = "GROUND_TRUTH"


class RiskBand(str, Enum):
    """Categorical risk tiers based on normalized score [0.0, 1.0]."""
    LOW = "LOW"             # [0.00, 0.40)
    MEDIUM = "MEDIUM"       # [0.40, 0.60)
    HIGH = "HIGH"           # [0.60, 0.75)
    CRITICAL = "CRITICAL"   # [0.75, 1.00]


