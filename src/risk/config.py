@dataclass(frozen=True)
class RiskWeightsConfig:
    """Configurable weights for the 6 candidate risk factors.

    Weights must be non-negative and sum to 1.0.
    """
    event_severity: float = 0.25
    geographic_exposure: float = 0.20
    supplier_criticality: float = 0.15
    product_criticality: float = 0.15
    dependency_strength: float = 0.15
    single_source_dependency: float = 0.10

    def __post_init__(self) -> None:
        total = (
            self.event_severity
            + self.geographic_exposure
            + self.supplier_criticality
            + self.product_criticality
            + self.dependency_strength
            + self.single_source_dependency
        )
        if not (0.999 <= total <= 1.001):
            raise ValueError(f"Risk factor weights must sum to 1.0 (current sum: {total:.4f})")

    def to_dict(self) -> dict[str, float]:
        """Convert weights to dictionary."""
        return {
            "event_severity": self.event_severity,
            "geographic_exposure": self.geographic_exposure,
            "supplier_criticality": self.supplier_criticality,
            "product_criticality": self.product_criticality,
            "dependency_strength": self.dependency_strength,
            "single_source_dependency": self.single_source_dependency,
        }


@dataclass
class DeterministicRiskConfig:
    """Master configuration for deterministic risk evaluation."""
    weights: RiskWeightsConfig = field(default_factory=RiskWeightsConfig)
    scale_to_100: bool = True  # Produce both [0,1] and [0,100] scale

    # Risk band thresholds on [0.0, 1.0] scale
    band_thresholds: tuple[tuple[float, RiskBand], ...] = (
        (0.75, RiskBand.CRITICAL),
        (0.60, RiskBand.HIGH),
        (0.40, RiskBand.MEDIUM),
        (0.00, RiskBand.LOW),
    )

    def determine_band(self, normalized_score: float) -> RiskBand:
        """Assign risk band based on normalized score [0.0, 1.0]."""
        for threshold, band in self.band_thresholds:
            if normalized_score >= threshold:
                return band
        return RiskBand.LOW


DEFAULT_DETERMINISTIC_CONFIG = DeterministicRiskConfig()
